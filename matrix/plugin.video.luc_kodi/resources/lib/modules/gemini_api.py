"""
	luc_kodi Add-on
	Gemini API client for AI-powered natural language search.

	v2 changes (debug version):
	- No module-level requests.Session / urllib3.Retry (some Android Kodi builds
	  fail silently on module import otherwise).
	- Manual cache via cache.cache_get/cache_insert (bypasses cache.get()'s
	  bare except that swallowed exceptions).
	- Diagnostic logging via xbmc.log(LOGERROR) which always shows regardless
	  of luc_kodi's debug.enabled setting. Search log for "[luc_kodi-gemini]".
	- Exposes last_error_message() so ai_search can display the real failure
	  reason to the user.
"""

